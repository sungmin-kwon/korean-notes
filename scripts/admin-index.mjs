// Writes ADMIN.md: every note, published or not, so hidden notes aren't forgotten.
// Runs before every build (`prebuild`), or by hand with `npm run admin`.
// ADMIN.md is in the repo, not on the site. The repo is public, so it is unlisted, not private.
import { writeFileSync } from 'node:fs';
import { readNotes } from './notes-meta.mjs';

const notes = readNotes();
const list = (v) => (Array.isArray(v) ? v : v ? [v] : []);
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');
const count = (s) => notes.filter((n) => n.status === s).length;

const rows = notes.map((n) => {
  const title = n.data.title ?? '(short note)';
  return `| ${n.status} | ${cell(n.data.date)} | [${cell(title)}](${n.file}) | ${cell(list(n.data.tags).join(', '))} | ${cell(list(n.data.model).join(', '))} |`;
});

const md = `# Admin index

Every note in \`src/content/notes/\`, including the ones not on the site.
Generated by \`npm run admin\` (also runs before every build); don't edit by hand.
This file is not deployed, but the repository is public, so anyone can read it and the hidden notes' source.

${notes.length} notes: ${count('visible')} visible, ${count('hidden')} hidden, ${count('draft')} draft.

| status | date | note | tags | model |
| --- | --- | --- | --- | --- |
${rows.join('\n')}

- **visible**: on the index, tag pages, RSS and search.
- **hidden**: finished but withheld (\`hidden: true\`). No page is built for it, and links to it from visible notes show as plain text.
- **draft**: unfinished (\`draft: true\`). Treated the same as hidden.

To put a hidden note back on the site, delete its \`hidden: true\` line, run \`npm run build\`, and commit the note together with the regenerated ADMIN.md. See WRITING.md, section 2.
`;

writeFileSync(new URL('../ADMIN.md', import.meta.url), md);
console.log(`ADMIN.md: ${count('visible')} visible, ${count('hidden')} hidden, ${count('draft')} draft`);
